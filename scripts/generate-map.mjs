// Builds src/content/map-data.ts: an azimuthal equidistant projection centred on Baku.
// On this projection every straight line from the centre is a great-circle route and
// distance from the centre is true distance, so the rings mark real kilometres.
//
// Usage: npm run generate:map   (re-run after editing src/content/places.json)

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { geoAzimuthalEquidistant, geoDistance, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const root = new URL("../", import.meta.url);
const { origin, places } = JSON.parse(readFileSync(new URL("src/content/places.json", root), "utf8"));
const land = JSON.parse(readFileSync(require.resolve("world-atlas/land-110m.json"), "utf8"));

const EARTH_KM = 6371;
const RADIUS_KM = 8000; // map extent
const SIZE = 640; // SVG viewBox size
const RADIUS_PX = 300;
const scale = RADIUS_PX / (RADIUS_KM / EARTH_KM);
const center = [origin.lon, origin.lat];

const projection = geoAzimuthalEquidistant()
  .rotate([-origin.lon, -origin.lat])
  .clipAngle(((RADIUS_KM / EARTH_KM) * 180) / Math.PI)
  .scale(scale)
  .translate([SIZE / 2, SIZE / 2])
  .precision(0.5);

const landPath = geoPath(projection).digits(1)(feature(land, land.objects.land));

const round = (n, d = 1) => Math.round(n * 10 ** d) / 10 ** d;
const points = places.map((p) => {
  const [x, y] = projection([p.lon, p.lat]);
  const dx = x - SIZE / 2;
  const dy = y - SIZE / 2;
  const len = Math.hypot(dx, dy);
  return {
    id: p.id,
    x: round(x),
    y: round(y),
    km: Math.round((geoDistance(center, [p.lon, p.lat]) * EARTH_KM) / 10) * 10,
    // unit vector from Baku (screen coordinates, y down) = true compass bearing
    ux: round(dx / len, 4),
    uy: round(dy / len, 4),
  };
});

const rings = [2000, 4000, 6000, 8000].map((km) => ({ km, r: round((scale * km) / EARTH_KM) }));

const out = `// Generated by scripts/generate-map.mjs. Do not edit by hand.
// Azimuthal equidistant projection centred on ${origin.city} (${origin.lat}° N, ${origin.lon}° E).

export const MAP_SIZE = ${SIZE};
export const MAP_RADIUS = ${RADIUS_PX};

export const rings = ${JSON.stringify(rings)} as const;

export const projected: Record<string, { x: number; y: number; km: number; ux: number; uy: number }> = ${JSON.stringify(
  Object.fromEntries(points.map(({ id, ...rest }) => [id, rest])),
  null,
  2,
)};

export const landPath =
  ${JSON.stringify(landPath)};
`;

writeFileSync(new URL("src/content/map-data.ts", root), out);
console.log(`map-data.ts written: ${points.length} places, land path ${landPath.length} chars`);
